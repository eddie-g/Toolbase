#!/usr/bin/env node
/*
 * Self-hosted web fonts for the PDF editor.
 *
 * Reads resources/fonts/editor-fonts.json, asks Google Fonts for the
 * stylesheet a current browser gets (woff2, one file per unicode-range
 * subset), downloads every file and writes:
 *
 *   public/fonts/editor/editor-fonts.css        the editor's families
 *   public/fonts/editor/signature/<family>.css  one per typed-signature family
 *   public/fonts/editor/files/<family>/...      the woff2 files
 *   public/fonts/editor/licenses/<family>.txt   each family's licence
 *
 * The output is committed: the editor must not depend on Google at run time
 * or at build time. Run this again to add a family or pick up new versions:
 *
 *   node scripts/fetch-editor-fonts.mjs
 *   node scripts/fetch-editor-fonts.mjs --signature   only the typed-signature families
 *
 * --signature leaves editor-fonts.css and its files alone, so changing the
 * signature list cannot move the editor's text onto a newer font version.
 *
 * The files are the ones the editor was already using from fonts.gstatic.com,
 * so text measures exactly as before.
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public', 'fonts', 'editor');
const BROWSER = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';
const LICENCE_PATHS = ['ofl/{slug}/OFL.txt', 'apache/{slug}/LICENSE.txt', 'ufl/{slug}/UFL.txt', 'ufl/{slug}/LICENCE.txt'];

const slugOf = (family) => family.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const repoSlugOf = (family) => family.toLowerCase().replace(/[^a-z0-9]+/g, '');

async function get(url, as = 'text') {
    for (let attempt = 1; ; attempt += 1) {
        try {
            const response = await fetch(url, { headers: { 'User-Agent': BROWSER } });
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            return as === 'text' ? await response.text() : Buffer.from(await response.arrayBuffer());
        } catch (error) {
            if (attempt >= 4) throw new Error(`${url}: ${error.message}`);
            await new Promise((resolve) => setTimeout(resolve, 500 * attempt));
        }
    }
}

/** Downloads every file a stylesheet names and returns it with local URLs. */
async function localise(css, urlPrefix) {
    const urls = Array.from(new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)]+/g) || []));
    const local = new Map();
    let bytes = 0;
    const queue = urls.slice();
    await Promise.all(Array.from({ length: 12 }, async () => {
        for (let url = queue.shift(); url; url = queue.shift()) {
            // https://fonts.gstatic.com/s/<family>/<version>/<file>.woff2
            const [, family, version, file] = new URL(url).pathname.match(/^\/s\/([^/]+)\/([^/]+)\/(.+)$/) || [];
            if (!family) throw new Error(`unexpected font URL ${url}`);
            const relative = path.posix.join('files', family, `${version}-${file}`);
            const data = await get(url, 'buffer');
            await mkdir(path.dirname(path.join(OUT, relative)), { recursive: true });
            await writeFile(path.join(OUT, relative), data);
            bytes += data.length;
            local.set(url, `${urlPrefix}${relative}`);
        }
    }));

    return { css: css.replace(/https:\/\/fonts\.gstatic\.com\/[^)]+/g, (url) => local.get(url)), files: urls.length, bytes };
}

async function licenceFor(family) {
    for (const template of LICENCE_PATHS) {
        try {
            return await get(`https://raw.githubusercontent.com/google/fonts/main/${template.replace('{slug}', repoSlugOf(family))}`);
        } catch (_) {
            // Try the next licence directory.
        }
    }
    throw new Error(`no licence found for ${family}`);
}

const signatureOnly = process.argv.includes('--signature');
const manifest = JSON.parse(await readFile(path.join(ROOT, 'resources', 'fonts', 'editor-fonts.json'), 'utf8'));
// Offered families first, then the ones kept only for signatures already typed in them.
const signatureFamilies = [...manifest.signature, ...(manifest.signatureLegacy || [])];
await rm(signatureOnly ? path.join(OUT, 'signature') : OUT, { recursive: true, force: true });
await mkdir(path.join(OUT, 'signature'), { recursive: true });
await mkdir(path.join(OUT, 'licenses'), { recursive: true });

if (!signatureOnly) {
    const query = Object.entries(manifest.editor)
        .map(([family, axes]) => `family=${encodeURIComponent(family).replace(/%20/g, '+')}${axes ? `:${axes}` : ''}`)
        .join('&');
    const editor = await localise(await get(`https://fonts.googleapis.com/css2?${query}&display=swap`), '');
    await writeFile(path.join(OUT, 'editor-fonts.css'), `/* Generated by scripts/fetch-editor-fonts.mjs. Do not edit. */\n${editor.css}`);
    console.log(`editor-fonts.css: ${Object.keys(manifest.editor).length} families, ${editor.files} files, ${(editor.bytes / 1048576).toFixed(1)} MB`);
}

let signatureBytes = 0;
for (const family of signatureFamilies) {
    let css;
    try {
        css = await get(`https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:${manifest.signatureAxes}&display=swap`);
    } catch (_) {
        // A family without a bold: ask for what it has.
        css = await get(`https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}&display=swap`);
    }
    const result = await localise(css, '../');
    signatureBytes += result.bytes;
    await writeFile(path.join(OUT, 'signature', `${slugOf(family)}.css`), `/* Generated by scripts/fetch-editor-fonts.mjs. Do not edit. */\n${result.css}`);
}
console.log(`signature: ${signatureFamilies.length} families, ${(signatureBytes / 1048576).toFixed(1)} MB`);

const licences = [];
for (const family of [...Object.keys(manifest.editor), ...signatureFamilies]) {
    const licencePath = path.join(OUT, 'licenses', `${slugOf(family)}.txt`);
    // --signature keeps the licences already on disk and fetches only the new ones.
    const text = await readFile(licencePath, 'utf8').catch(() => licenceFor(family));
    await writeFile(licencePath, text);
    licences.push(`| ${family} | ${/SIL Open Font License/i.test(text) ? 'SIL Open Font License 1.1' : /Apache License/i.test(text) ? 'Apache License 2.0' : /Ubuntu Font Licence/i.test(text) ? 'Ubuntu Font Licence 1.0' : 'see file'} | licenses/${slugOf(family)}.txt |`);
}
await writeFile(path.join(OUT, 'README.md'), [
    '# Web fonts of the PDF editor',
    '',
    'Generated by `scripts/fetch-editor-fonts.mjs` from `resources/fonts/editor-fonts.json`.',
    'The files are the woff2 subsets Google Fonts serves; each family is used under its own licence:',
    '',
    '| Family | Licence | Text |',
    '|---|---|---|',
    ...licences,
    '',
].join('\n'));
console.log(`licences: ${licences.length}`);
